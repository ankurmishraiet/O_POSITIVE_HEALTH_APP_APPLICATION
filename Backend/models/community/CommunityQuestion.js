const mongoose = require("mongoose");

// Keep this list in sync with CATEGORIES in the mobile app screen
const CATEGORIES = [
  "General Surgery",
  "Orthopedics",
  "Cardiology",
  "Ophthalmology",
  "Gynecology",
  "Urology",
  "Insurance",
  "Medical Loan",
  "Other",
];

const answerSchema = new mongoose.Schema(
  {
    authorName: { type: String, default: "Guest", trim: true, maxlength: 60 },
    authorId: { type: String, default: null },
    // Only the admin endpoint can set this to true
    isExpert: { type: Boolean, default: false },
    text: { type: String, required: true, trim: true, maxlength: 3000 },
    likedBy: { type: [String], default: [] },
  },
  { timestamps: true }
);

const questionSchema = new mongoose.Schema(
  {
    authorName: { type: String, default: "Guest", trim: true, maxlength: 60 },
    // Logged-in userId, or a device id generated by the app for guests
    authorId: { type: String, required: true, index: true },
    category: { type: String, enum: CATEGORIES, default: "Other", index: true },
    question: { type: String, required: true, trim: true, minlength: 10, maxlength: 500 },
    helpfulBy: { type: [String], default: [] },
    answers: { type: [answerSchema], default: [] },
    // "approved" shows in the feed. Set COMMUNITY_MODERATION=on to start as "pending"
    status: {
      type: String,
      enum: ["pending", "approved", "rejected"],
      default: "approved",
      index: true,
    },
  },
  { timestamps: true }
);

questionSchema.index({ createdAt: -1 });

const CommunityQuestion = mongoose.model("CommunityQuestion", questionSchema);

module.exports = CommunityQuestion;
module.exports.CATEGORIES = CATEGORIES;